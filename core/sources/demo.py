class DemoSource(ChatSource):
    key = "demo"
    label = "内置样例数据（免配置，用于试用与验收）"
    hint = "不读取任何真实微信数据。建议第一次使用时先跑这个，确认产出格式符合预期。"
    needs_path = False

    def list_contacts(self) -> List[Contact]:
        out: List[Contact] = []
        for cid, raw in _RAW.items():
            msgs = raw["msgs"]
            out.append(
                Contact(
                    cid=cid,
                    name=raw["name"],
                    kind=raw["kind"],
                    alias=raw["alias"],
                    msg_count=len(msgs),
                    last_time=_d(msgs[-1][0], msgs[-1][1], msgs[-1][2]),
                )
            )
        return sorted(out, key=lambda c: c.last_time or datetime.min, reverse=True)

    def fetch(self, contact: Contact, start: date, end: date) -> List[Message]:
        raw = _RAW.get(contact.cid)
        if not raw:
            return []
        lo, hi = self.day_bounds(start, end)
        out: List[Message] = []
        for days_ago, hh, mm, sender, text in raw["msgs"]:
            ts = _d(days_ago, hh, mm)
            if lo <= ts <= hi:
                out.append(
                    Message(ts=ts, sender=sender, text=text, is_self=(sender == "我"))
                )
        return self.sort_messages(out)
